#!/usr/bin/env python3
"""Extract the audio-decoder/NetEq dependency closure from Google's GN->CMake map.

No upstream installer or application is executed. Generated files stay in build/.
"""
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'research/upstream/webrtc-neteq'


def main():
    (ROOT/'build').mkdir(exist_ok=True)
    text=(SOURCE/'linux_x86_64.cmake').read_text()
    registry={};dependencies={}
    for command,body in re.findall(r'(?m)^(add_library|target_link_libraries)\(([^\n]*)\)',text):
        args=body.split();target=args[0]
        if command=='add_library':registry[target]=args[1:]
        else:dependencies[target]=[p for p in args[1:] if p not in ['PUBLIC','PRIVATE','INTERFACE']]
    # The upstream Opus GN target groups encoders with decoders. This client
    # already has an uplink encoder; remove that branch and its network-adaptor
    # and protobuf dependencies rather than building another complete sender.
    for name in ['webrtc_modules_audio_coding_webrtc_opus','webrtc_modules_audio_coding_webrtc_multiopus']:
        registry[name]=[p for p in registry[name] if '/audio_encoder_' not in p]
        dependencies[name]=[p for p in dependencies[name] if 'audio_network_adaptor' not in p and 'protobuf_utils' not in p]
    visited=set();external=set()
    def visit(name):
        if name in visited:return
        if name not in registry:external.add(name);return
        visited.add(name)
        for dep in dependencies.get(name,[]):visit(dep)
    for name in ['webrtc_modules_audio_coding_default_neteq_factory','webrtc_api_audio_codecs_opus_audio_decoder_factory']:visit(name)
    assert external==set(p for p in external if p.startswith('absl::'))|{'opus','webrtc_fft_size_256','webrtc_spl_sqrt_floor'},external
    files=sorted({p.replace('${WEBRTC_ROOT}/','') for name in visited for p in registry[name] if '${WEBRTC_ROOT}/' in p}|
                 {'common_audio/third_party/ooura/fft_size_256/fft4g.cc','common_audio/third_party/spl_sqrt_floor/spl_sqrt_floor.c'})
    assert all((SOURCE/p).is_file() for p in files)
    output=['# Generated by scripts/prepare_neteq.py; decoder-only upstream closure.','set(ALISA_NETEQ_SOURCES']
    output.extend('  "${NETEQ_ROOT}/'+p+'"' for p in files);output.append(')')
    output.append('set(ALISA_NETEQ_ABSL '+' '.join(sorted(p for p in external if p.startswith('absl::')))+')')
    (ROOT/'build/neteq-sources.cmake').write_text('\n'.join(output)+'\n')
    (ROOT/'build/neteq-subset.json').write_text(json.dumps({'upstream':'bf2ad1344a1f4c5150d8a0a88f70d0424223bc50','target_count':len(visited),'source_count':len(files),'sources':files,'external_dependencies':sorted(external),'excluded':'Opus encoders / network-adaptor / protobuf; x86 SIMD excluded only for ARM'},indent=2)+'\n')
    print(f'Prepared NetEq decoder subset: {len(files)} source files, {len(visited)} GN targets; no browser/transport/encoder.')


if __name__=='__main__':main()
